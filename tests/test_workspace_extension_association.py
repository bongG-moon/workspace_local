"""Opt-in execution of association functions under disposable HKCU test keys.

Set WORKSPACE_EXTENSION_ASSOCIATION_TEST=1. This compiles only a tiny harness,
never runs Setup and never writes the live Software\\Classes associations.
"""
import os
from pathlib import Path
import subprocess
import tempfile
import unittest
import uuid


ROOT = Path(__file__).resolve().parents[1]
COMPILER = ROOT / 'build/nsis/portable-3.12/nsis-3.12/makensis.exe'


@unittest.skipUnless(os.name == 'nt' and COMPILER.is_file() and
                     os.environ.get('WORKSPACE_EXTENSION_ASSOCIATION_TEST') == '1',
                     'Opt-in isolated Windows registry/NSIS fixture')
class ExtensionAssociationExecutionTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        import winreg
        cls.reg = winreg
        cls.temp = tempfile.TemporaryDirectory(prefix='association-fixture-', dir=ROOT / 'build')
        cls.addClassCleanup(cls.temp.cleanup)
        cls.root = Path(cls.temp.name)
        cls.key = 'Software\\AXWorkspaceExtensionAssociationTests\\' + uuid.uuid4().hex
        cls.classes = cls.key + '\\Classes'
        cls.progid = cls.classes + r'\AX.Workspace.Extension'
        cls.ext = cls.classes + r'\.axextension'
        cls.command = cls.progid + r'\shell\open\command'
        cls.installed = cls.root / '설치 경로 & 공백'
        cls.expected = f'"{cls.installed}\\AX-Workspace.exe" --import-extension "%1"'
        cls.addClassCleanup(cls.cleanup_keys)
        source = (ROOT / 'deploy/AX-Workspace.nsi').read_text(encoding='utf-8-sig')
        register = 'Function RegisterExtensionPackage' + source.split('Function RegisterExtensionPackage', 1)[1].split('FunctionEnd', 1)[0] + 'FunctionEnd'
        unregister = 'Function UnregisterExtensionPackage' + source.split('Function un.UnregisterExtensionPackage', 1)[1].split('FunctionEnd', 1)[0] + 'FunctionEnd'
        functions = (register + '\n' + unregister).replace(r'Software\Classes', cls.classes)
        # The real default/program ownership logic executes unchanged. The
        # shell notification is unnecessary because these are not associations.
        functions = functions.replace("System::Call 'shell32::SHChangeNotify(i 0x08000000, i 0, p 0, p 0)'", 'DetailPrint "fixture keys updated"')
        for product, name in [('AX.Workspace.Desktop', 'normal'), ('AX.Workspace.Desktop.Test.fixture', 'diagnostic')]:
            script = cls.root / (name + '.nsi')
            exe = cls.root / (name + '.exe')
            script.write_text('''Unicode true
RequestExecutionLevel user
SilentInstall silent
!include "LogicLib.nsh"
!include "FileFunc.nsh"
!define EXTENSION_PROGID "AX.Workspace.Extension"
!define PRODUCT_ID "''' + product + '''"
OutFile "''' + str(exe) + '''"
Var Operation
Function .onInit
  SetShellVarContext current
  SetRegView 64
  StrCpy $INSTDIR "''' + str(cls.installed) + '''"
  ${GetParameters} $R0
  ${GetOptions} $R0 "/ACTION=" $Operation
FunctionEnd
''' + functions + '''
Section
  ${If} $Operation == "register"
    Call RegisterExtensionPackage
  ${ElseIf} $Operation == "unregister"
    Call UnregisterExtensionPackage
  ${Else}
    SetErrorLevel 3
  ${EndIf}
SectionEnd
''', encoding='utf-8-sig')
            result = subprocess.run([str(COMPILER), '/NOCONFIG', '/V2', '/INPUTCHARSET', 'UTF8', str(script)],
                                    capture_output=True, timeout=30, creationflags=subprocess.CREATE_NO_WINDOW)
            if result.returncode:
                raise AssertionError(result.stdout + result.stderr)
        cls.normal = cls.root / 'normal.exe'
        cls.diagnostic = cls.root / 'diagnostic.exe'

    @classmethod
    def cleanup_keys(cls):
        # This sole root is freshly generated by this fixture, never live Classes.
        assert cls.key.startswith('Software\\AXWorkspaceExtensionAssociationTests\\')
        def remove(path):
            try:
                with cls.reg.OpenKey(cls.reg.HKEY_CURRENT_USER, path, 0,
                                     cls.reg.KEY_ALL_ACCESS | cls.reg.KEY_WOW64_64KEY) as handle:
                    children = []
                    index = 0
                    while True:
                        try:
                            children.append(cls.reg.EnumKey(handle, index))
                        except OSError:
                            break
                        index += 1
                for child in children:
                    remove(path + '\\' + child)
                cls.reg.DeleteKeyEx(cls.reg.HKEY_CURRENT_USER, path, cls.reg.KEY_WOW64_64KEY)
            except FileNotFoundError:
                pass
        remove(cls.key)
        try:
            cls.reg.DeleteKeyEx(cls.reg.HKEY_CURRENT_USER, 'Software\\AXWorkspaceExtensionAssociationTests', cls.reg.KEY_WOW64_64KEY)
        except OSError:
            pass

    def setUp(self):
        self.cleanup_keys()

    def write(self, path, value, name=''):
        with self.reg.CreateKeyEx(self.reg.HKEY_CURRENT_USER, path, 0,
                                  self.reg.KEY_WRITE | self.reg.KEY_WOW64_64KEY) as handle:
            self.reg.SetValueEx(handle, name, 0, self.reg.REG_SZ, value)

    def read(self, path, name=''):
        try:
            with self.reg.OpenKey(self.reg.HKEY_CURRENT_USER, path, 0,
                                  self.reg.KEY_READ | self.reg.KEY_WOW64_64KEY) as handle:
                return self.reg.QueryValueEx(handle, name)[0]
        except FileNotFoundError:
            return None

    def run_action(self, action, *, diagnostic=False):
        result = subprocess.run([str(self.diagnostic if diagnostic else self.normal), '/S', '/ACTION=' + action],
                                stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, timeout=15,
                                creationflags=subprocess.CREATE_NO_WINDOW)
        self.assertEqual(0, result.returncode)

    def test_quoted_command_and_icon_register_and_owned_uninstall(self):
        self.run_action('register')
        self.assertEqual('AX.Workspace.Extension', self.read(self.ext))
        self.assertEqual(self.expected, self.read(self.command))
        self.assertEqual(f'"{self.installed}\\AX-Workspace.exe",0', self.read(self.progid + r'\DefaultIcon'))
        self.run_action('unregister')
        self.assertIsNone(self.read(self.ext))
        self.assertIsNone(self.read(self.command))

    def test_existing_different_default_is_preserved_on_install_and_remove(self):
        self.write(self.ext, 'Another.Application')
        self.write(self.ext + r'\OpenWithProgids', '', 'Another.Application')
        self.run_action('register')
        self.assertEqual('Another.Application', self.read(self.ext))
        self.assertEqual(self.expected, self.read(self.command))
        self.run_action('unregister')
        self.assertEqual('Another.Application', self.read(self.ext))
        self.assertEqual('', self.read(self.ext + r'\OpenWithProgids', 'Another.Application'))
        self.assertIsNone(self.read(self.ext + r'\OpenWithProgids', 'AX.Workspace.Extension'))

    def test_foreign_program_command_is_not_overwritten_or_removed(self):
        foreign = '"C:\\Other app\\AX-Workspace.exe" --import-extension "%1"'
        self.write(self.command, foreign)
        self.write(self.ext, 'AX.Workspace.Extension')
        self.run_action('register')
        self.assertEqual(foreign, self.read(self.command))
        self.run_action('unregister')
        self.assertEqual(foreign, self.read(self.command))
        self.assertEqual('AX.Workspace.Extension', self.read(self.ext))

    def test_takeover_after_our_install_is_preserved(self):
        self.run_action('register')
        self.write(self.command, '"C:\\New location\\AX-Workspace.exe" --import-extension "%1"')
        self.run_action('unregister')
        self.assertEqual('AX.Workspace.Extension', self.read(self.ext))
        self.assertIsNotNone(self.read(self.command))
        self.assertEqual('', self.read(self.ext + r'\OpenWithProgids', 'AX.Workspace.Extension'))

    def test_diagnostic_installer_never_takes_the_normal_association(self):
        self.run_action('register', diagnostic=True)
        self.assertIsNone(self.read(self.command))
        self.assertIsNone(self.read(self.ext))
        self.run_action('register')
        self.run_action('unregister', diagnostic=True)
        self.assertEqual(self.expected, self.read(self.command))
